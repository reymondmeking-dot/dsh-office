'use strict'
const { contextBridge, ipcRenderer, webUtils } = require('electron')

contextBridge.exposeInMainWorld('office', {
  init: () => ipcRenderer.invoke('office:init'),
  browser: (action, args = {}) => ipcRenderer.invoke('office:browser', action, args),
  detectCli: () => ipcRenderer.invoke('office:detectCli'),
  saveCliResources: input => ipcRenderer.invoke('office:saveCliResources', input),
  envList: () => ipcRenderer.invoke('office:envList'),
  envScan: () => ipcRenderer.invoke('office:envScan'),
  envImport: input => ipcRenderer.invoke('office:envImport', input),
  envUpdate: (name, patch) => ipcRenderer.invoke('office:envUpdate', name, patch),
  envDelete: name => ipcRenderer.invoke('office:envDelete', name),
  setLang: l => ipcRenderer.invoke('office:setLang', l),
  submit: input => ipcRenderer.invoke('office:submit', input),
  rush: on => ipcRenderer.invoke('office:rush', on),
  setModel: (id, key) => ipcRenderer.invoke('office:setModel', id, key),
  setEffort: (id, e) => ipcRenderer.invoke('office:setEffort', id, e),
  setDefaultEffort: e => ipcRenderer.invoke('office:setDefaultEffort', e),
  providerInfo: () => ipcRenderer.invoke('office:providerInfo'),
  scanAgents: () => ipcRenderer.invoke('office:scanAgents'),
  discover: req => ipcRenderer.invoke('office:discover', req),
  testModel: req => ipcRenderer.invoke('office:testModel', req),
  codexScan: () => ipcRenderer.invoke('office:codexScan'),
  codexApply: req => ipcRenderer.invoke('office:codexApply', req),
  pathOf: file => { try { return webUtils.getPathForFile(file) || '' } catch { return '' } },
  pickFiles: () => ipcRenderer.invoke('office:pickFiles'),
  statPaths: list => ipcRenderer.invoke('office:statPaths', list),
  answer: (answers) => ipcRenderer.invoke('office:answer', answers),
  rename: (id, name) => ipcRenderer.invoke('office:rename', id, name),
  saveProvider: (route, p, key, models) => ipcRenderer.invoke('office:saveProvider', route, p, key, models),
  deleteProvider: route => ipcRenderer.invoke('office:deleteProvider', route),
  projects: () => ipcRenderer.invoke('office:projects'),
  taskLocation: input => ipcRenderer.invoke('office:taskLocation', input),
  projectPreview: input => ipcRenderer.invoke('office:projectPreview', input),
  createProject: input => ipcRenderer.invoke('office:createProject', input),
  conversations: id => ipcRenderer.invoke('office:conversations', id),
  createConversation: (id, input) => ipcRenderer.invoke('office:createConversation', id, input),
  setConversationReferences: (id, cid, refs) => ipcRenderer.invoke('office:setConversationReferences', id, cid, refs),
  files: id => ipcRenderer.invoke('office:files', id),
  readFile: p => ipcRenderer.invoke('office:readFile', p),
  readImage: p => ipcRenderer.invoke('office:readImage', p),
  chatHistory: (id, cid) => ipcRenderer.invoke('office:chatHistory', id, cid),
  chatSend: (id, text, cid) => ipcRenderer.invoke('office:chatSend', id, text, cid),
  open: p => ipcRenderer.invoke('office:open', p),
  reveal: p => ipcRenderer.invoke('office:reveal', p),
  harness: n => ipcRenderer.invoke('office:harness', n),
  saveHarness: (n, t) => ipcRenderer.invoke('office:saveHarness', n, t),
  harnessDir: () => ipcRenderer.invoke('office:harnessDir'),
  pickDir: () => ipcRenderer.invoke('office:pickDir'),
  saveSettings: s => ipcRenderer.invoke('office:saveSettings', s),
  openLog: () => ipcRenderer.invoke('office:openLog'),
  extInfo: () => ipcRenderer.invoke('office:extInfo'),
  saveExt: patch => ipcRenderer.invoke('office:saveExt', patch),
  testMcp: server => ipcRenderer.invoke('office:testMcp', server),
  installPlugin: dir => ipcRenderer.invoke('office:installPlugin', dir),
  removePlugin: id => ipcRenderer.invoke('office:removePlugin', id),
  pluginDir: () => ipcRenderer.invoke('office:pluginDir'),
  readSkill: (source, name) => ipcRenderer.invoke('office:readSkill', source, name),
  saveSkill: s => ipcRenderer.invoke('office:saveSkill', s),
  deleteSkill: name => ipcRenderer.invoke('office:deleteSkill', name),
  importSkill: kind => ipcRenderer.invoke('office:importSkill', kind),
  skillDir: () => ipcRenderer.invoke('office:skillDir'),
  reloadSkills: () => ipcRenderer.invoke('office:reloadSkills'),
  onEvent: fn => ipcRenderer.on('office:event', (_e, ev) => fn(ev)),
  onAgent: fn => ipcRenderer.on('office:agent', (_e, a) => fn(a)),
  win: { min: () => ipcRenderer.send('win:min'), max: () => ipcRenderer.send('win:max'), close: () => ipcRenderer.send('win:close') },
})
